create table public.rank_system_versions (
    id uuid primary key default gen_random_uuid(),
    version_number bigint generated by default as identity unique not null,
    name text not null,
    description text,
    formula_key text not null,
    input_schema_version integer not null,
    term_schema_version integer not null,
    rubric_version integer not null,
    rubric_semantics_key text not null,
    contract jsonb not null,
    contract_hash text not null unique,
    created_by text,
    created_at timestamptz not null default now(),
    constraint rank_system_versions_version_positive
        check (version_number >= 1),
    constraint rank_system_versions_name_bounded
        check (length(name) between 1 and 128),
    constraint rank_system_versions_description_bounded
        check (description is null or length(description) <= 4096),
    constraint rank_system_versions_formula_key_bounded
        check (length(formula_key) between 1 and 128),
    constraint rank_system_versions_schema_versions_positive
        check (input_schema_version >= 1 and term_schema_version >= 1),
    constraint rank_system_versions_rubric_version_positive
        check (rubric_version >= 1),
    constraint rank_system_versions_rubric_semantics_bounded
        check (length(rubric_semantics_key) between 1 and 128),
    constraint rank_system_versions_contract_valid
        check (jsonb_typeof(contract) = 'object'
               and pg_catalog.pg_column_size(contract) <= 32768),
    constraint rank_system_versions_hash_valid
        check (contract_hash ~ '^sha256:[0-9a-f]{64}$'),
    constraint rank_system_versions_created_by_bounded
        check (created_by is null or length(created_by) <= 256)
);

