create table public.rank_experiments (
    id uuid primary key default gen_random_uuid(),
    rank_system_version_id uuid not null
        references public.rank_system_versions(id),
    name text not null,
    pipeline_namespace text not null,
    source_run_id uuid,
    parent_experiment_id uuid references public.rank_experiments(id),
    rerun_of_experiment_id uuid references public.rank_experiments(id),
    status text not null default 'draft',
    validation_profile text not null default 'full',
    config jsonb not null,
    config_hash text not null,
    preprocessing_config jsonb not null default '{}'::jsonb,
    data_cutoff_at timestamptz,
    data_snapshot_hash text,
    context_set_hash text,
    code_commit text,
    metrics jsonb,
    failure_reason text,
    started_at timestamptz,
    finished_at timestamptz,
    created_at timestamptz not null default now(),
    unique (id, rank_system_version_id),
    constraint rank_experiments_name_bounded
        check (length(name) between 1 and 128),
    constraint rank_experiments_namespace_valid
        check (pipeline_namespace in ('complex_v1', 'simple_v1', 'legacy_import')),
    constraint rank_experiments_status_valid
        check (status in (
            'draft', 'running', 'calculated', 'validated', 'rejected',
            'failed', 'promoted'
        )),
    constraint rank_experiments_validation_profile_valid
        check (validation_profile in ('full', 'legacy_import')),
    constraint rank_experiments_legacy_profile_consistent
        check (validation_profile <> 'legacy_import'
               or pipeline_namespace = 'legacy_import'),
    constraint rank_experiments_config_valid
        check (jsonb_typeof(config) = 'object'
               and pg_catalog.pg_column_size(config) <= 65536),
    constraint rank_experiments_preprocessing_valid
        check (jsonb_typeof(preprocessing_config) = 'object'
               and pg_catalog.pg_column_size(preprocessing_config) <= 65536),
    constraint rank_experiments_config_hash_valid
        check (config_hash ~ '^sha256:[0-9a-f]{64}$'),
    constraint rank_experiments_data_hash_valid
        check (data_snapshot_hash is null
               or data_snapshot_hash ~ '^(sha256|legacy):[0-9a-z-]+$'),
    constraint rank_experiments_context_hash_valid
        check (context_set_hash is null
               or context_set_hash ~ '^(sha256|legacy):[0-9a-z-]+$'),
    constraint rank_experiments_code_commit_bounded
        check (code_commit is null or length(code_commit) <= 128),
    constraint rank_experiments_metrics_valid
        check (metrics is null or (
            jsonb_typeof(metrics) = 'object'
            and pg_catalog.pg_column_size(metrics) <= 131072
        )),
    constraint rank_experiments_failure_bounded
        check (failure_reason is null or length(failure_reason) <= 4096),
    constraint rank_experiments_window_valid
        check (started_at is null or finished_at is null or started_at <= finished_at)
);

comment on table public.rank_experiments is
    'One immutable ranking configuration and result cohort. source_run_id plus pipeline_namespace identifies its clustering input without coupling ranking history to deletable source-run tables.';
comment on column public.rank_experiments.validation_profile is
    'full for every normal experiment. legacy_import is a one-time order-preserving bootstrap exemption and cannot validate future candidates.';

create unique index rank_experiments_one_legacy_import_idx
    on public.rank_experiments (validation_profile)
    where validation_profile = 'legacy_import';
create index rank_experiments_source_run_idx
    on public.rank_experiments (pipeline_namespace, source_run_id)
    where source_run_id is not null;
create index rank_experiments_created_idx
    on public.rank_experiments (created_at desc, id);

create function public.protect_rank_experiment_payload()
returns trigger
language plpgsql
set search_path = ''
as $fn$
begin
    if new.id is distinct from old.id
       or new.rank_system_version_id is distinct from old.rank_system_version_id
       or new.name is distinct from old.name
       or new.pipeline_namespace is distinct from old.pipeline_namespace
       or new.source_run_id is distinct from old.source_run_id
       or new.parent_experiment_id is distinct from old.parent_experiment_id
       or new.rerun_of_experiment_id is distinct from old.rerun_of_experiment_id
       or new.validation_profile is distinct from old.validation_profile
       or new.config is distinct from old.config
       or new.config_hash is distinct from old.config_hash
       or new.preprocessing_config is distinct from old.preprocessing_config
       or new.data_cutoff_at is distinct from old.data_cutoff_at
       or new.data_snapshot_hash is distinct from old.data_snapshot_hash
       or new.context_set_hash is distinct from old.context_set_hash
       or new.code_commit is distinct from old.code_commit
       or new.started_at is distinct from old.started_at
       or new.created_at is distinct from old.created_at then
        raise exception 'rank experiment inputs and provenance are immutable'
            using errcode = '55000';
    end if;
    return new;
end;
$fn$;

create trigger rank_experiments_payload_immutable
before update on public.rank_experiments
for each row execute function public.protect_rank_experiment_payload();

