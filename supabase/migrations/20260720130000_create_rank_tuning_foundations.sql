               or (category_id is not null and category_position >= 1)),
    constraint snapshot_rank_rows_rank_key_finite
        check (primary_rank_key > '-Infinity'::float8
               and primary_rank_key < 'Infinity'::float8),
    constraint snapshot_rank_rows_context_hash_valid
        check (context_hash ~ '^(md5:[0-9a-f]{32}|sha256:[0-9a-f]{64}|legacy:[0-9a-z-]+)$'),
    constraint snapshot_rank_rows_input_consistent
        check ((rank_input is null) = (rank_input_hash is null)),
    constraint snapshot_rank_rows_input_valid
        check (rank_input is null or (
            jsonb_typeof(rank_input) = 'object'
            and pg_catalog.pg_column_size(rank_input) <= 65536
        )),
    constraint snapshot_rank_rows_input_hash_valid
        check (rank_input_hash is null
               or rank_input_hash ~ '^sha256:[0-9a-f]{64}$'),
