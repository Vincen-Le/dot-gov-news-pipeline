create table public.rank_position_opinions (
    experiment_id uuid not null,
    rank_system_version_id uuid not null,
    golden_event_card_id uuid not null,
    category_id uuid not null,
    current_category_position integer not null,
    suggested_category_position integer,
    position_delta integer,
    direction text not null,
    status text not null,
    reason text,
    neighbor_card_ids uuid[] not null default '{}',
    comparison_evidence jsonb not null default '[]'::jsonb,
    consistent_comparisons integer not null default 0,
    total_comparisons integer not null default 0,
    judge_model text,
    prompt_version integer,
    input_hash text,
    created_at timestamptz not null default now(),
    primary key (experiment_id, rank_system_version_id, golden_event_card_id),
    foreign key (experiment_id, rank_system_version_id, golden_event_card_id)
        references public.snapshot_rank_rows(
            experiment_id, rank_system_version_id, golden_event_card_id
        ),
    constraint rank_position_opinions_positions_valid
        check (current_category_position >= 1
               and (suggested_category_position is null
                    or suggested_category_position >= 1)),
    constraint rank_position_opinions_direction_valid
        check (direction in ('up', 'down', 'stay', 'uncertain')),
    constraint rank_position_opinions_status_valid
        check (status in (
            'available', 'bounded', 'not_run', 'insufficient_neighbors',
            'inconsistent', 'failed'
        )),
    constraint rank_position_opinions_available_consistent
        check (status <> 'available' or (
            suggested_category_position is not null
            and position_delta = suggested_category_position - current_category_position
        )),
    constraint rank_position_opinions_bounded_consistent
        check (status <> 'bounded' or (
            suggested_category_position is null
            and position_delta is not null
            and position_delta <> 0
            and direction in ('up', 'down')
        )),
    constraint rank_position_opinions_direction_consistent
        check (
            (direction = 'up' and position_delta < 0)
            or (direction = 'down' and position_delta > 0)
            or (direction = 'stay' and position_delta = 0)
            or (direction = 'uncertain' and position_delta is null)
        ),
    constraint rank_position_opinions_reason_bounded
        check (reason is null or length(reason) <= 4096),
    constraint rank_position_opinions_evidence_valid
        check (jsonb_typeof(comparison_evidence) = 'array'
               and pg_catalog.pg_column_size(comparison_evidence) <= 131072),
    constraint rank_position_opinions_counts_valid
        check (consistent_comparisons >= 0
               and total_comparisons >= consistent_comparisons),
    constraint rank_position_opinions_model_bounded
        check (judge_model is null or length(judge_model) <= 256),
    constraint rank_position_opinions_prompt_valid
        check (prompt_version is null or prompt_version >= 1),
    constraint rank_position_opinions_input_hash_valid
        check (input_hash is null or input_hash ~ '^sha256:[0-9a-f]{64}$')
);

comment on table public.rank_position_opinions is
    'Immutable category-relative LLM placement recommendation. bounded means every inspected neighbor should be crossed but the audit window ended before an exact destination was proven.';

create table public.golden_rank_state (
    id text primary key default 'primary',
    active_experiment_id uuid not null,
    active_rank_system_version_id uuid not null,
    activated_at timestamptz not null default now(),
    activated_by text,
    constraint golden_rank_state_singleton check (id = 'primary'),
    constraint golden_rank_state_activated_by_bounded
        check (activated_by is null or length(activated_by) <= 256),
    foreign key (active_experiment_id, active_rank_system_version_id)
        references public.rank_experiments(id, rank_system_version_id)
);

comment on table public.golden_rank_state is
    'Database-enforced zero-or-one singleton pointer selecting the complete active ranking experiment. Direct writes are revoked; promotion RPCs own changes.';

create view public.golden_rank_rows
with (security_invoker = true)
as
select
    ranked.golden_event_card_id,
    ranked.storyline_id,
    ranked.primary_rank_key,
    ranked.rank_terms,
    ranked.rank_input,
    ranked.context_hash,
    ranked.card_snapshot,
    ranked.context_snapshot,
    ranked.global_position,
    ranked.category_id,
    ranked.category_position,
    ranked.experiment_id,
    ranked.rank_system_version_id
from public.golden_rank_state active
join public.snapshot_rank_rows ranked
  on ranked.experiment_id = active.active_experiment_id
 and ranked.rank_system_version_id = active.active_rank_system_version_id;

comment on view public.golden_rank_rows is
    'Active immutable rank rows selected atomically by golden_rank_state. primary_rank_key is derived from the selected experiment, never copied back into golden cards.';

